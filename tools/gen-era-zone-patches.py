#!/usr/bin/env python3
"""Generates modules/goomba_era/data/*: zone.yaml patches that do what two of LandSandBoat's era SQL
files did before zone settings moved from the zone_settings table to data/zones/<zone>/zone.yaml:

  era/sql/abyssea/cop_level_restrictions.sql  ->  abyssea_cop_level_caps/  (level_restriction)
  era/sql/abyssea/job_adjustments.sql, Mazurka ->  abyssea_mazurka/         (misc: mazurka)

Run it against the LandSandBoat checkout named in LSB_REF whenever you move to a newer one:

  python3 tools/gen-era-zone-patches.py /opt/goomba/server

Patches replace the whole `misc` list (RFC 7396), so they are regenerated from that checkout's
own zone files rather than written by hand.
"""
import pathlib
import shutil
import subprocess
import sys

import yaml

if len(sys.argv) != 2:
    sys.exit(__doc__)
lsb = pathlib.Path(sys.argv[1])
zones = lsb / "data" / "zones"
if not zones.is_dir():
    sys.exit(f"{zones} not found: pass a LandSandBoat checkout")

out = pathlib.Path(__file__).resolve().parent.parent / "modules" / "goomba_era" / "data"
try:
    commit = subprocess.run(["git", "-c", "safe.directory=*", "-C", str(lsb), "rev-parse", "--short", "HEAD"],
                            capture_output=True, text=True, check=True).stdout.strip()
except (OSError, subprocess.CalledProcessError):
    commit = "unknown"

# CoP mission areas, level caps before the 06/21/2010 update (values from cop_level_restrictions.sql).
COP_CAPS = {
    "promyvion_holla": 30,
    "promyvion_dem": 30,
    "promyvion_mea": 30,
    "promyvion_vahzl": 50,
    "phomiuna_aqueducts": 40,
    "sacrarium": 50,
    "riverne_site_b01": 50,
    "riverne_site_a01": 40,
}


def write(folder: str, zone: str, header: str, body: str) -> None:
    path = out / folder / "zones" / zone / "zone.yaml"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f"{header}# Generated by tools/gen-era-zone-patches.py from LandSandBoat {commit}.\n\n{body}\n")


for folder in ("abyssea_cop_level_caps", "abyssea_mazurka"):
    shutil.rmtree(out / folder, ignore_errors=True)

for zone, cap in COP_CAPS.items():
    if not (zones / zone / "zone.yaml").exists():
        print(f"warning: no zone {zone}; skipped", file=sys.stderr)
        continue
    write(
        "abyssea_cop_level_caps",
        zone,
        "# CoP mission area level cap before the June 21, 2010 update.\n"
        "# Source: https://www.bg-wiki.com/ffxi/Version_Update_(06/21/2010)\n",
        f"level_restriction: {cap}",
    )

changed = 0
for zone_file in sorted(zones.glob("*/zone.yaml")):
    doc = yaml.safe_load(zone_file.read_text()) or {}
    types = doc.get("type") or []
    misc = list(doc.get("misc") or [])
    town_or_field = "city" in types or "outdoors" in types
    if town_or_field and "mazurka" not in misc:
        misc.append("mazurka")
    elif not town_or_field and "mazurka" in misc:
        misc.remove("mazurka")
    else:
        continue
    changed += 1
    write(
        "abyssea_mazurka",
        zone_file.parent.name,
        "# Mazurka usable in towns and fields only, before the September 8, 2010 update.\n"
        "# Source: https://www.bg-wiki.com/ffxi/Version_Update_(09/08/2010)\n",
        "misc: [" + ", ".join(misc) + "]",
    )

print(f"wrote {len(COP_CAPS)} level-cap patches and {changed} Mazurka patches under {out}")
